% generate_project_statistics.m
% Auto-generates PROJECT_STATISTICS.md for the root directory

function generate_project_statistics()
    disp('Generating Project Statistics...');
    
    scriptPath = mfilename('fullpath');
    [scriptDir, ~, ~] = fileparts(scriptPath);
    [rootDir, ~, ~] = fileparts(scriptDir);
    
    origDir = pwd;
    cd(rootDir);
    cleanupDir = onCleanup(@() cd(origDir));
    
    % Safe directory traversal that prunes protected path ('re solution prompt') BEFORE recursing into it
    mFiles = []; pyFiles = []; csvFiles = []; htmlFiles = []; mdFiles = []; matFiles = [];
    
    q = {rootDir};
    while ~isempty(q)
        currDir = q{1};
        q(1) = [];
        
        try
            items = dir(currDir);
        catch
            continue;
        end
        
        for k = 1:length(items)
            itemName = items(k).name;
            if strcmp(itemName, '.') || strcmp(itemName, '..')
                continue;
            end
            
            itemPath = fullfile(currDir, itemName);
            
            % CRITICAL SAFETY: Never open, list, scan, or enter the protected folder
            if contains(lower(itemPath), 're solution prompt') || contains(itemName, '.git') || contains(itemName, '.kilo')
                continue;
            end
            
            if items(k).isdir
                q{end+1} = itemPath; %#ok<AGROW>
            else
                [~, ~, ext] = fileparts(itemName);
                s = struct('name', itemName, 'folder', currDir, 'bytes', items(k).bytes, 'date', items(k).date);
                if strcmpi(ext, '.m')
                    if isempty(mFiles), mFiles = s; else, mFiles(end+1) = s; end
                elseif strcmpi(ext, '.py')
                    if isempty(pyFiles), pyFiles = s; else, pyFiles(end+1) = s; end
                elseif strcmpi(ext, '.csv')
                    if isempty(csvFiles), csvFiles = s; else, csvFiles(end+1) = s; end
                elseif strcmpi(ext, '.html')
                    if isempty(htmlFiles), htmlFiles = s; else, htmlFiles(end+1) = s; end
                elseif strcmpi(ext, '.md')
                    if isempty(mdFiles), mdFiles = s; else, mdFiles(end+1) = s; end
                elseif strcmpi(ext, '.mat')
                    if isempty(matFiles), matFiles = s; else, matFiles(end+1) = s; end
                end
            end
        end
    end
    
    totalMLines = 0;
    for i = 1:length(mFiles)
        try
            str = fileread(fullfile(mFiles(i).folder, mFiles(i).name));
            totalMLines = totalMLines + length(regexp(str, '\n')) + 1;
        catch
        end
    end
    
    numMFiles = length(mFiles);
    numPyFiles = length(pyFiles);
    numCsvFiles = length(csvFiles);
    numHtmlFiles = length(htmlFiles);
    numMdFiles = length(mdFiles);
    numModels = length(matFiles);
    
    fid = fopen('PROJECT_STATISTICS.md', 'w');
    fprintf(fid, '# Project Statistics\n\n');
    fprintf(fid, 'This document is automatically generated by `scripts/generate_project_statistics.m`.\n\n');
    fprintf(fid, '| Metric | Count |\n');
    fprintf(fid, '|---|---|\n');
    fprintf(fid, '| MATLAB Files (`.m`) | %d |\n', numMFiles);
    fprintf(fid, '| Python Files (`.py`) | %d |\n', numPyFiles);
    fprintf(fid, '| Lines of MATLAB Code | ~%d |\n', totalMLines);
    fprintf(fid, '| Datasets (`.csv`) | %d |\n', numCsvFiles);
    fprintf(fid, '| Saved Models (`.mat`) | %d |\n', numModels);
    fprintf(fid, '| HTML Reports (`.html`) | %d |\n', numHtmlFiles);
    fprintf(fid, '| Markdown Documentation (`.md`) | %d |\n', numMdFiles);
    
    fprintf(fid, '\n## Dependencies\n');
    fprintf(fid, '- Statistics and Machine Learning Toolbox\n');
    fprintf(fid, '- Deep Learning Toolbox\n');
    fprintf(fid, '- Text Analytics Toolbox\n');
    fprintf(fid, '- Econometrics Toolbox\n');
    fprintf(fid, '\n## Technical Indicators\n');
    fprintf(fid, 'All technical indicators (SMA, EMA, MACD, RSI, Bollinger Bands, ATR, VWAP) are implemented\n');
    fprintf(fid, 'using base MATLAB (`movmean`, `movstd`, custom EMA/RSI loops). **Financial Toolbox is not required**\n');
    fprintf(fid, 'and is not used. See `src/indicators/IndicatorEngine.m`.\n');
    
    fclose(fid);
    
    disp('Generated PROJECT_STATISTICS.md successfully.');
end
